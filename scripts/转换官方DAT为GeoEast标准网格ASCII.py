import argparse
import math
from pathlib import Path


def parse_official_dat(path: Path, origin_mode: str):
    samples = []
    line_to_x = {}
    cmp_to_y = {}

    with path.open("r", encoding="utf-8", errors="ignore") as f:
        for raw in f:
            text = raw.strip()
            if not text or text.startswith("#"):
                continue
            parts = text.split()
            if len(parts) < 5:
                continue
            try:
                line_no = int(float(parts[0]))
                cmp_no = int(float(parts[1]))
                x = float(parts[2])
                y = float(parts[3])
                value = float(parts[4])
            except ValueError:
                continue
            samples.append((line_no, cmp_no, x, y, value))
            line_to_x.setdefault(line_no, x)
            cmp_to_y.setdefault(cmp_no, y)

    if not samples:
        raise RuntimeError(f"未读取到有效 DAT 采样点：{path}")

    lines = sorted(line_to_x)
    cmps = sorted(cmp_to_y)
    nx = len(lines)
    ny = len(cmps)
    if nx < 2 or ny < 2:
        raise RuntimeError("网格行列数量不足，无法推断网格间距。")

    dx = abs(line_to_x[lines[1]] - line_to_x[lines[0]])
    dy = abs(cmp_to_y[cmps[1]] - cmp_to_y[cmps[0]])
    if dx <= 0 or dy <= 0:
        raise RuntimeError("网格间距推断失败，请检查 DAT 文件中的 X/Y 坐标。")

    sx_center = line_to_x[lines[0]]
    sy_center = cmp_to_y[cmps[0]]
    if origin_mode == "cell-corner":
        sx = sx_center - 0.5 * dx
        sy = sy_center - 0.5 * dy
        max_x = sx + nx * dx
        max_y = sy + ny * dy
    else:
        sx = sx_center
        sy = sy_center
        max_x = sx + (nx - 1) * dx
        max_y = sy + (ny - 1) * dy

    line_index = {v: i for i, v in enumerate(lines)}
    cmp_index = {v: j for j, v in enumerate(cmps)}
    values = [[math.nan for _ in range(ny)] for _ in range(nx)]
    for line_no, cmp_no, _x, _y, value in samples:
        values[line_index[line_no]][cmp_index[cmp_no]] = value

    missing = sum(1 for col in values for v in col if math.isnan(v))
    if missing:
        raise RuntimeError(f"DAT 文件不是完整规则网格，缺失 {missing} 个采样点。")

    return {
        "nx": nx,
        "ny": ny,
        "sx": sx,
        "sy": sy,
        "dx": dx,
        "dy": dy,
        "max_x": max_x,
        "max_y": max_y,
        "origin_mode": origin_mode,
        "min_value": min(v for col in values for v in col),
        "max_value": max(v for col in values for v in col),
        "values": values,
    }


def write_geoeast_grid_ascii(grid, output: Path, grid_name: str, null_value: float):
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# GeoEast Grid ASCII generated by FaultPolyTrace\n")
        f.write("# Header rows below are designed for GeoEast Import Grid Header Item mapping.\n")
        f.write(f"# OriginMode {grid['origin_mode']}\n")
        f.write("# Body columns: X Y GridValue\n")
        f.write(f"GridName {grid_name}\n")
        f.write(f"MinimumX {grid['sx']:.6f}\n")
        f.write(f"MinimumY {grid['sy']:.6f}\n")
        f.write(f"MaximumX {grid['max_x']:.6f}\n")
        f.write(f"MaximumY {grid['max_y']:.6f}\n")
        f.write(f"XGridSpacing {grid['dx']:.6f}\n")
        f.write(f"YGridSpacing {grid['dy']:.6f}\n")
        f.write(f"XGridNumber {grid['nx']}\n")
        f.write(f"YGridNumber {grid['ny']}\n")
        f.write(f"MinimumValue {grid['min_value']:.8g}\n")
        f.write(f"MaximumValue {grid['max_value']:.8g}\n")
        f.write(f"NullValue {null_value:.8g}\n")
        f.write("X Y GridValue\n")
        for i in range(grid["nx"]):
            x = grid["sx"] + (i + 0.5) * grid["dx"]
            for j in range(grid["ny"]):
                y = grid["sy"] + j * grid["dy"] if grid["origin_mode"] == "sample-center" else grid["sy"] + (j + 0.5) * grid["dy"]
                x_out = grid["sx"] + i * grid["dx"] if grid["origin_mode"] == "sample-center" else x
                f.write(f"{x_out:.6f} {y:.6f} {grid['values'][i][j]:.8g}\n")


