def main():
    parser = argparse.ArgumentParser(description="将赛题7官方 test.dat 转为便于 GeoEast Import Grid 的标准网格 ASCII。")
    parser.add_argument("--input", required=True, help="官方 test.dat 路径")
    parser.add_argument("--output", required=True, help="输出 ASCII 网格路径")
    parser.add_argument("--grid-name", default="test7_fault_attribute_ascii", help="写入文件头的网格名")
    parser.add_argument("--null-value", type=float, default=-9999.0, help="GeoEast 空值")
    parser.add_argument(
        "--origin-mode",
        choices=["sample-center", "cell-corner"],
        default="sample-center",
        help="GeoEast 手工导入建议使用 sample-center，与官方 test.dat 的 X/Y 采样点坐标一致。",
    )
    args = parser.parse_args()

    src = Path(args.input)
    dst = Path(args.output)
    grid = parse_official_dat(src, args.origin_mode)
    write_geoeast_grid_ascii(grid, dst, args.grid_name, args.null_value)
    write_import_guide(grid, dst, args.grid_name, dst)

    print("转换完成")
    print(f"输入：{src}")
    print(f"输出：{dst}")
    print(f"网格：nx={grid['nx']} ny={grid['ny']} sx={grid['sx']:.6f} sy={grid['sy']:.6f} dx={grid['dx']:.6f} dy={grid['dy']:.6f}")


if __name__ == "__main__":
    main()
